-- dbo.usp_EtlRunStart @JobName, @LoadId → SELECT public.etl_run_start(job, id)
CREATE FUNCTION public.etl_run_start(p_job_name VARCHAR(128), p_load_id INTEGER)
RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE v_id INTEGER;
BEGIN
    INSERT INTO public.etl_run_log AS l (job_name, load_id) VALUES (p_job_name, p_load_id)
    RETURNING l.run_log_id INTO v_id;
    RETURN v_id;
END $$;
