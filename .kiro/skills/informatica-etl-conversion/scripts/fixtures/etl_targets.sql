-- Replaces the T-SQL variable batch in the target Pre SQL (IC-10 / IC-11)
CREATE FUNCTION public.etl_pre_dim_customer() RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE v_cnt INTEGER;
BEGIN
    SELECT COUNT(*) INTO v_cnt FROM public.dim_customer;
    IF v_cnt = 0 THEN
        INSERT INTO public.dim_customer (customer_id, first_name, last_name, email, is_current)
        VALUES (-1, 'Unknown', 'Unknown', 'unknown@example.com', TRUE);
    END IF;
    RETURN v_cnt;
END $$;

