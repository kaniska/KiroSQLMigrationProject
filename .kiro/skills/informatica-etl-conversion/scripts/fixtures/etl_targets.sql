-- dbo.usp_ArchiveOldOrders @Days (Source Pre Load stored procedure) → function
CREATE TABLE public.orders_archive (LIKE public.orders);
CREATE FUNCTION public.archive_old_orders(p_days INTEGER) RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE v_n INTEGER;
BEGIN
    INSERT INTO public.orders_archive
    SELECT o.* FROM public.orders o
    WHERE  o.created_at < LOCALTIMESTAMP - make_interval(days => p_days) AND o.status = 'Cancelled';
    GET DIAGNOSTICS v_n = ROW_COUNT;
    RETURN v_n;
END $$;

-- dbo.usp_CalculateShipping (connected Stored Procedure transformation).
-- Trimmed stand-in for the project's converted public.calculate_shipping.
CREATE FUNCTION public.calculate_shipping(p_order_id INTEGER, p_ship_to_zip VARCHAR(10), p_is_expedited BOOLEAN DEFAULT FALSE)
RETURNS TABLE(order_id INTEGER, shipping_cost NUMERIC(19,4))
LANGUAGE sql STABLE AS $$
    SELECT o.order_id,
           CASE WHEN o.total_amount >= 50 THEN 0
                ELSE ROUND(COALESCE(SUM(p.weight_lbs * ol.quantity), 0) * 1.10, 2) * CASE WHEN p_is_expedited THEN 1.5 ELSE 1 END
           END::NUMERIC(19,4)
    FROM   public.orders o
    JOIN   public.order_lines ol ON ol.order_id = o.order_id
    JOIN   public.products p ON p.product_id = ol.product_id
    WHERE  o.order_id = p_order_id
    GROUP  BY o.order_id, o.total_amount;
$$;

