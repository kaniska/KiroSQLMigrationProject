-- dbo.usp_LogLoad @TableName, @LoadId  →  SELECT public.etl_log_load(name, id)
CREATE FUNCTION public.etl_log_load(p_table_name VARCHAR(128), p_load_id INTEGER)
RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE v_id INTEGER;
BEGIN
    INSERT INTO public.etl_load_log AS l (table_name, load_id) VALUES (p_table_name, p_load_id)
    RETURNING l.log_id INTO v_id;
    RETURN v_id;
END $$;

